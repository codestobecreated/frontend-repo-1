export function getCitiesForStates(statesList: string[]): string[] {
  const result: string[] = [];
  statesList.forEach((state) => {
    const list = CITIES[state] || [];
    list.forEach((city) => {
      if (!result.includes(city)) result.push(city);
    });
  });
  return result;
}
